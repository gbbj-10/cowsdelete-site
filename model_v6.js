// 그런포스 NB 32-125.1/116 — 공개 3면도(정면·측면·평면)에서 읽은 치수로 만든 참고용 3D (단위 mm)
// 좌표: X = 축 방향(측면도 가로), Y = 정면도 가로(축 중심 0), Z = 높이(축 높이 23.1)
const A = 23.1;                         // 축 높이
const ax = [0, 0, A];
// 1) 모터: 둥근 사각 몸통 (폭 178, 높이 178, 모서리 R30) + 팬 커버
const motor0 = prism('YZ', { rrect: [160, 160, 34], at: [0, A] }, -242.5, 8);
// 냉각핀: 네 면에 11.6 간격, 두께 2, 몸통 밖으로 9 (측면도·평면도에서 읽음)
const fins = [];
for (let k = -4; k <= 4; k++) {
  const z = A + k * 11.6, y = k * 11.6;
  fins.push(box([-213.9, 79, z - 1], [7.6, 89, z + 1]), box([-213.9, -89, z - 1], [7.6, -79, z + 1]));
  fins.push(box([-213.9, y - 1, A + 79], [7.6, y + 1, A + 89]), box([-213.9, y - 1, A - 89], [7.6, y + 1, A - 79]));
}
const motor = union(motor0, ...fins);
const fan = union(prism('YZ', { rrect: [172, 172, 40], at: [0, A] }, -274, -242.5),
                  prism('YZ', { rrect: [150, 150, 40], at: [0, A] }, -281.2, -274),
                  prism('YZ', { rrect: [110, 110, 40], at: [0, A] }, -285.9, -281.2));   // 팬 커버 끝 볼록면 (전체 길이 548.3)
const endShield = cyl([8, 0, A], [16.9, 0, A], 73.4);
// 2) 단자함
const tbox = union(box([-178.5, -78, 112], [-81.8, 78, 132.6]),
  ...[[-185.6, -40.7], [-185.6, 40.7], [-74.6, -40.7], [-74.6, 40.7]].map(([x, y]) => cyl([x, y, 106], [x, y, 116], 5)));   // 단자함 고정 나사 자리 4-Ø10 (평면도)
// 3) 들어 올리는 고리 (양옆)
// 고리: 평면도의 원(바깥 R18·안 R10, 중심 Y ±107)과 정면도의 두께(Z 19.1~27.1)
const eye = y => union(cut(cyl([-129.7, y, 19.1], [-129.7, y, 27.1], 18), cyl([-129.7, y, 15], [-129.7, y, 31], 10)),
                       box([-137.7, Math.sign(y) * 86, 19.1], [-121.7, Math.sign(y) * 92, 27.1]));
const lug1 = eye(107), lug2 = eye(-107);
// 4) 모터 플랜지 · 어댑터
const flange = union(cyl([16.9, 0, A], [26.9, 0, A], 73.4), cyl([26.9, 0, A], [48.9, 0, A], 99));
// 5) 랜턴 브래킷: 사각 틀(폭 ±66, 높이 ±59) + 양옆 창 + 커플링 덮개판(±81~98)
let lantern = box([48.9, -66, A - 59], [110.9, 66, A + 59]);
lantern = cut(lantern, box([62.9, -70, A - 45.6], [92.9, 70, A + 45.6]));
lantern = union(lantern, cyl([48.9, 0, A], [110.9, 0, A], 24),
  box([52.9, 81, A - 45.6], [102.9, 98, A + 45.6]), box([52.9, -98, A - 45.6], [102.9, -81, A + 45.6]));
// 6) 펌프 덮개 플랜지 + 볼류트(회전체 근사) + 흡입 목
const cover = cut(cyl([110.9, 0, A], [125.9, 0, A], 115), box([105, -130, -120], [130, 130, -80.9]));
const volute0 = revolve(ax, 'X', [[0, 125.9], [117, 125.9], [117, 182.4], [104, 196], [90, 207.4], [70, 217], [48, 224.3], [45, 228.5], [45, 262.4], [0, 262.4]]);
const volute = cut(volute0, box([120, -130, -130], [250, 130, -80.9]));
// ★ 핵심 치수 (배면도·평면도의 원에서 읽음, 그런포스 STEP 과 같음)
// 7) 흡입: 노즐 관 Ø90(볼류트에 포함) + 구경 Ø50, 플랜지 링 외경 Ø165 · 안지름 Ø90 · 두께 18, 볼트 구멍 4-Ø19 PCD 125 (45° 배치)
const PCD_S = 125, PCD_D = 100, HOLE = 19;
let suc = cut(cyl([244.4, 0, A], [262.4, 0, A], 82.5), cyl([240, 0, A], [270, 0, A], 45));
for (const a of [45, 135, 225, 315]) { const y = PCD_S / 2 * Math.cos(a * Math.PI / 180), z = A + PCD_S / 2 * Math.sin(a * Math.PI / 180); suc = cut(suc, cyl([240, y, z], [270, y, z], HOLE / 2)); }
// 8) 토출: 노즐 관 Ø70 · 구경 Ø32 (위로 163.1까지), 플랜지 링 외경 Ø140 · 안지름 Ø70 · 두께 16, 볼트 구멍 4-Ø19 PCD 100
const neck = cyl([182.4, 0, A], [182.4, 0, 163.1], 35);
let dis = cut(cyl([182.4, 0, 147.1], [182.4, 0, 163.1], 70), cyl([182.4, 0, 140], [182.4, 0, 170], 35));
for (const a of [45, 135, 225, 315]) { const x = 182.4 + PCD_D / 2 * Math.cos(a * Math.PI / 180), y = PCD_D / 2 * Math.sin(a * Math.PI / 180); dis = cut(dis, cyl([x, y, 140], [x, y, 170], HOLE / 2)); }
// 9) 다리 (양쪽 판 + 가운데 받침)
// 9) 다리: 판 100 × 50 × 14 (양쪽), ★ 고정용 U자 홈 4개 — 폭 12(R6), 홈 끝 중심 X 147.4 / 217.4 (간격 70), Y ±70 (간격 140), 다리 끝에서 안쪽으로 열림
let foot = union(box([132.4, 45, -88.9], [232.4, 95, -74.9]), box([132.4, -95, -88.9], [232.4, -45, -74.9]),
                 box([136.9, -49, -80.9], [227.9, 49, -40]));
for (const y of [-70, 70]) {
  foot = cut(foot, cyl([147.4, y, -95], [147.4, y, -70], 6), box([125, y - 6, -95], [147.4, y + 6, -70]));
  foot = cut(foot, cyl([217.4, y, -95], [217.4, y, -70], 6), box([217.4, y - 6, -95], [240, y + 6, -70]));
}
part('P1', '모터', 'blue', union(motor, fan, endShield, tbox, lug1, lug2));
part('P2', '모터 플랜지', 'metal', flange);
part('P3', '랜턴 브래킷', 'metal', lantern);
part('P4', '펌프 케이싱', 'blue', cut(union(cover, volute, neck, foot), cyl([200, 0, A], [270, 0, A], 25), cyl([182.4, 0, A + 40], [182.4, 0, 170], 16)));
part('P5', '흡입 플랜지', 'blue', suc);
part('P6', '토출 플랜지', 'blue', dis);
